#!/usr/bin/env python3
"""Resize originals in photos/ into publishable copies.

Writes:
  assets/photos/sm/<id>.jpg   640px long side (cards, months, gallery)
  assets/photos/lg/<id>.jpg   1600px long side (hero, lightbox)
  assets/og.jpg               1200x630 WhatsApp preview from the hero photo
  js/photos.js                manifest: const PHOTOS = [{id, w, h}, ...]

id = lowercased filename stem, non-alphanumerics -> '-'. Month photos keep
their folder: photos/months/m01.jpg -> id 'months/m01'.
Re-run after adding photos (e.g. months 1-3). Needs Pillow.
"""
import json
import re
import sys
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "photos"
OUT = ROOT / "assets" / "photos"
HERO_ID = "whatsapp-image-2026-11-09-at-12-26-01-am"   # keep in sync with CONTENT.hero in js/content.js
HERO_FOCUS_Y = 0.35           # vertical focal point for the OG crop
SIZES = {"sm": (640, 76), "lg": (1600, 80)}
EXTS = {".jpg", ".jpeg", ".png", ".webp"}


def slug(stem: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", stem.lower()).strip("-")


def load(path: Path) -> Image.Image:
    im = ImageOps.exif_transpose(Image.open(path))
    return im.convert("RGB")


def save_sizes(im: Image.Image, pid: str) -> tuple[int, int]:
    dims = im.size
    for folder, (edge, quality) in SIZES.items():
        dest = OUT / folder / f"{pid}.jpg"
        dest.parent.mkdir(parents=True, exist_ok=True)
        copy = im.copy()
        copy.thumbnail((edge, edge), Image.LANCZOS)
        copy.save(dest, "JPEG", quality=quality, optimize=True, progressive=True)
        if folder == "lg":
            dims = copy.size
    return dims


def save_og(im: Image.Image) -> None:
    w, h = im.size
    target = 1200 / 630
    if w / h > target:  # too wide: crop sides
        nw = int(h * target)
        box = ((w - nw) // 2, 0, (w - nw) // 2 + nw, h)
    else:  # too tall: crop around focal point
        nh = int(w / target)
        top = min(max(int(h * HERO_FOCUS_Y - nh / 2), 0), h - nh)
        box = (0, top, w, top + nh)
    og = im.crop(box).resize((1200, 630), Image.LANCZOS)
    for q in (82, 74, 66, 58):
        og.save(ROOT / "assets" / "og.jpg", "JPEG", quality=q, optimize=True, progressive=True)
        if (ROOT / "assets" / "og.jpg").stat().st_size < 300_000:
            break


def main() -> int:
    if not SRC.is_dir():
        print(f"missing {SRC}", file=sys.stderr)
        return 1
    manifest = []
    files = sorted(p for p in SRC.iterdir() if p.suffix.lower() in EXTS)
    months = sorted(p for p in (SRC / "months").glob("*") if p.suffix.lower() in EXTS) if (SRC / "months").is_dir() else []
    for path in files + months:
        pid = slug(path.stem)
        if path.parent.name == "months":
            pid = f"months/{pid}"
        im = load(path)
        w, h = save_sizes(im, pid)
        manifest.append({"id": pid, "w": w, "h": h})
        if pid == HERO_ID:
            save_og(im)
        print(f"ok {pid} {w}x{h}")
    body = ",\n  ".join(json.dumps(m) for m in manifest)
    (ROOT / "js" / "photos.js").write_text(
        "// GENERATED by tools/prepare-photos.py. Do not edit by hand.\n"
        f"const PHOTOS = [\n  {body}\n];\n",
        encoding="utf-8",
    )
    print(f"{len(manifest)} photos -> js/photos.js")
    return 0


if __name__ == "__main__":
    sys.exit(main())
